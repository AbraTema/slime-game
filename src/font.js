const cache = new Map();

/**
 * Render text to a canvas. scale = pixel size, color = fill, shadow = 1px drop-shadow/outline colour.
 */
export function textCanvas(text, { color = '#fff3d6', outline = '#1a1420', scale = 1, spacing = 1 } = {}) {
  text = String(text).toUpperCase();
  const key = [text, color, outline, scale, spacing].join('|');
  if (cache.has(key)) return cache.get(key);
  const glyphW = (ch) => (ch === ' ' ? 3 : 5);
  let w = 0;
  for (const ch of text) w += glyphW(ch) + spacing;
  w = Math.max(1, w - spacing);
  const pad = outline ? 1 : 0;
  const W = (w + pad * 2) * scale, H = (7 + pad * 2) * scale;
  const c = document.createElement('canvas');
  c.width = W; c.height = H;
  const x = c.getContext('2d');
  const plot = (px, py, col) => { x.fillStyle = col; x.fillRect(px * scale, py * scale, scale, scale); };
  const pass = (col, offs) => {
    let cx = pad;
    for (const ch of text) {
      const g = G[ch];
      if (g) g.forEach((row, ry) => { for (let rx = 0; rx < 5; rx++) if (row[rx] === '#') offs.forEach(([dx, dy]) => plot(cx + rx + dx, pad + ry + dy, col)); });
      cx += glyphW(ch) + spacing;
    }
  };
  if (outline) pass(outline, [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]);
  pass(color, [[0, 0]]);
  cache.set(key, c);
  return c;
}

/** Add pixel text as an image in a Phaser scene. Returns the Image; call setPixelText to update. */
export function addText(scene, x, y, text, opts = {}) {
  const img = scene.add.image(x, y, '__DEFAULT');
  img._ptOpts = opts;
  setPixelText(img, text);
  if (opts.origin) img.setOrigin(...opts.origin);
  return img;
}

export function setPixelText(img, text) {
  if (img._ptText === text) return img;
  img._ptText = text;
  const scene = img.scene;
  const c = textCanvas(text, img._ptOpts);
  const key = `pt_${c.width}x${c.height}_${String(text).toUpperCase()}_${img._ptOpts.color ?? ''}_${img._ptOpts.scale ?? 1}`;
  if (!scene.textures.exists(key)) scene.textures.addCanvas(key, c);
  img.setTexture(key);
  return img;
}
